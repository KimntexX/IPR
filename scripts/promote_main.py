#!/usr/bin/env python3
"""Promote a tested dev commit to main as a snapshot of its published paths.

Rule of 1 November 2026: main carries production code and documentation;
tests and analytic tracking stay on dev. A promotion commit holds exactly the
[main] paths of packaging/main-allowlist.txt taken from one dev commit, plus
release-manifest.json, with the promotion branch (issued from main) as its only
parent: dev never enters main's ancestry. Markdown links to dev-only paths are
pointed at that dev commit on GitHub, so main has no dead link; every other
file is copied byte for byte and recorded with its SHA-256 in the manifest.

Without --write the promotion is only checked and summarised. Nothing touches
the working tree: the commit is built through a temporary Git index.
"""
import argparse
import hashlib
import json
import os
import posixpath
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ALLOWLIST = 'packaging/main-allowlist.txt'
MANIFEST = 'release-manifest.json'
REPOSITORY = 'https://github.com/KimntexX/IPR'


def parse_allowlist(text):
    """Sections [main] and [dev] of pattern lines; comments start with #."""
    sections, current = {'main': [], 'dev': []}, None
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('[') and line.endswith(']'):
            current = line[1:-1]
            if current not in sections:
                raise ValueError(f'{ALLOWLIST}:{number}: unknown section {line}')
            continue
        if current is None:
            raise ValueError(f'{ALLOWLIST}:{number}: pattern outside a section')
        sections[current].append(line)
    return sections


def pattern_regex(pattern):
    """"*" within a segment, "**" across segments, "?" one character; a
    trailing "/" covers the whole folder."""
    if pattern.endswith('/'):
        pattern += '**'
    out, i = '', 0
    while i < len(pattern):
        if pattern.startswith('**', i):
            out, i = out + '.*', i + 2
        elif pattern[i] == '*':
            out, i = out + '[^/]*', i + 1
        elif pattern[i] == '?':
            out, i = out + '[^/]', i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile(out + r'\Z')


def classify(paths, sections):
    """Paths of each side, and those matching no side or both."""
    rules = {side: [pattern_regex(p) for p in patterns] for side, patterns in sections.items()}
    result = {'main': [], 'dev': [], 'unclassified': [], 'ambiguous': []}
    for path in paths:
        sides = [side for side, regexes in rules.items() if any(r.match(path) for r in regexes)]
        if len(sides) == 1:
            result[sides[0]].append(path)
        else:
            result['ambiguous' if sides else 'unclassified'].append(path)
    return result


LINK = re.compile(r'(\]\(|href=")([^)"\s]+)')


def git(*args, input=None, env=None):
    return subprocess.run(['git', *args], cwd=ROOT, input=input, env=env, check=True,
                          capture_output=True).stdout


def tree_entries(commit):
    """{path: (mode, blob)} of the regular files and links of a commit."""
    entries = {}
    for record in git('ls-tree', '-r', '-z', commit).split(b'\0'):
        if not record:
            continue
        meta, path = record.split(b'\t', 1)
        mode, kind, blob = meta.decode().split()
        if kind != 'blob':
            raise ValueError(f'Unsupported entry {kind} at {path.decode()}')
        entries[path.decode('utf-8')] = (mode, blob)
    return entries


def read_blobs(blobs):
    contents = {}
    for blob in blobs:
        contents[blob] = git('cat-file', 'blob', blob)
    return contents


def write_blob(data):
    return git('hash-object', '-w', '--stdin', input=data).decode().strip()


def plan(commit, allowlist_text):
    """Classification, rewritten documents and manifest of a promotion."""
    sections = parse_allowlist(allowlist_text)
    entries = tree_entries(commit)
    if MANIFEST in entries:
        raise ValueError(f'{MANIFEST} is generated by the promotion, not versioned on dev')
    groups = classify(sorted(entries), sections)
    published = groups['main']
    dev_paths = set(groups['dev'])
    main_folders = set()
    for path in published:
        directory = posixpath.dirname(path)
        while directory:
            main_folders.add(directory)
            directory = posixpath.dirname(directory)
    contents = read_blobs({entries[p][1] for p in published})
    files, blobs = [], {}
    for path in published:
        mode, blob = entries[path]
        data = contents[blob]
        record = {'path': path, 'mode': mode, 'sha256': hashlib.sha256(data).hexdigest()}
        if path.endswith('.md'):
            text = data.decode('utf-8')
            rewritten = rewrite_document(text, path, dev_paths, main_folders, commit)
            if rewritten != text:
                data = rewritten.encode('utf-8')
                record['source_sha256'] = record['sha256']
                record['sha256'] = hashlib.sha256(data).hexdigest()
                record['links_to_dev'] = True
        blobs[path] = (mode, data, blob if 'source_sha256' not in record else None)
        files.append(record)
    allowlist_sha = hashlib.sha256(allowlist_text.encode('utf-8')).hexdigest()
    manifest = {
        'schema': 1,
        'source': {'repository': REPOSITORY, 'commit': commit},
        'allowlist': {'path': ALLOWLIST, 'sha256': allowlist_sha},
        'excluded_files': len(dev_paths),
        'files': files,
    }
    return groups, blobs, manifest


def rewrite_document(text, path, dev_paths, main_folders, commit):
    """Relative Markdown links to dev-only files or folders become links to
    that dev commit on GitHub; links within main are left as they are."""
    def replace(match):
        prefix, target = match.groups()
        if re.match(r'^[a-z][a-z0-9+.-]*:|^#|^/', target, re.IGNORECASE):
            return match.group(0)
        relative, anchor = (target.split('#', 1) + [''])[:2]
        if not relative:
            return match.group(0)
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(path), relative))
        if resolved.startswith('..'):
            return match.group(0)
        suffix = '#' + anchor if anchor else ''
        if resolved in dev_paths:
            return f'{prefix}{REPOSITORY}/blob/{commit}/{resolved}{suffix}'
        if resolved not in main_folders and any(p.startswith(resolved + '/') for p in dev_paths):
            return f'{prefix}{REPOSITORY}/tree/{commit}/{resolved}{suffix}'
        return match.group(0)
    return LINK.sub(replace, text)


def commit_promotion(commit, parent, blobs, manifest, message):
    """Commit of the promoted tree on top of parent, through a temporary index."""
    with tempfile.TemporaryDirectory() as directory:
        env = dict(os.environ, GIT_INDEX_FILE=os.path.join(directory, 'index'))
        lines = []
        for path, (mode, data, blob) in blobs.items():
            lines.append(f'{mode} {blob or write_blob(data)}\t{path}')
        manifest_data = (json.dumps(manifest, indent=1, ensure_ascii=False) + '\n').encode('utf-8')
        lines.append(f'100644 {write_blob(manifest_data)}\t{MANIFEST}')
        git('update-index', '--add', '--index-info', input=('\n'.join(lines) + '\n').encode('utf-8'), env=env)
        tree = git('write-tree', env=env).decode().strip()
    return git('commit-tree', tree, '-p', parent, '-m', message).decode().strip()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--source', required=True, help='tested dev commit')
    parser.add_argument('--parent', default='main', help='commit the promotion follows (default main)')
    parser.add_argument('--branch', default='main_promotion', help='branch set to the promotion with --write')
    parser.add_argument('--label', default='', help='release label, for the commit message')
    parser.add_argument('--write', action='store_true', help='create the commit and move --branch to it')
    args = parser.parse_args(argv)
    commit = git('rev-parse', '--verify', args.source + '^{commit}').decode().strip()
    parent = git('rev-parse', '--verify', args.parent + '^{commit}').decode().strip()
    allowlist_text = git('show', f'{commit}:{ALLOWLIST}').decode('utf-8')
    groups, blobs, manifest = plan(commit, allowlist_text)
    linked = sum(1 for f in manifest['files'] if f.get('links_to_dev'))
    print(f'Source {commit}: {len(groups["main"])} files to main ({linked} documents linked to dev), '
          f'{len(groups["dev"])} kept on dev.')
    problems = [('Unclassified', groups['unclassified']), ('In both sections', groups['ambiguous'])]
    for title, paths in problems:
        for path in paths:
            print(f'{title}: {path}', file=sys.stderr)
    if groups['unclassified'] or groups['ambiguous']:
        print(f'Classify these paths in {ALLOWLIST} on dev, then test that commit again.', file=sys.stderr)
        return 1
    if not args.write:
        print('Dry run: nothing written.')
        return 0
    label = f' {args.label}' if args.label else ''
    message = (f'release{label}: promote dev {commit[:12]} to main\n\n'
               f'Snapshot of the paths published on main ({ALLOWLIST}), taken from the tested\n'
               f'dev commit {commit}; tests and analytic tracking stay on dev.\n'
               f'File hashes in {MANIFEST}.\n')
    promoted = commit_promotion(commit, parent, blobs, manifest, message)
    git('update-ref', f'refs/heads/{args.branch}', promoted)
    print(f'{args.branch} -> {promoted}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
